def rr(x, y, w, h, r):
    """Plain rounded-rect path (no signature cut) for small tiles."""
    return (f'M{x+r} {y}H{x+w-r}A{r} {r} 0 0 1 {x+w} {y+r}V{y+h-r}A{r} {r} 0 0 1 {x+w-r} {y+h}'
            f'H{x+r}A{r} {r} 0 0 1 {x} {y+h-r}V{y+r}A{r} {r} 0 0 1 {x+r} {y}Z')


def cut(x, y, w, h, r, c):
    """Rounded rect with a small signature cut on the top-right (for small tiles)."""
    return (f'M{x+r} {y}H{x+w-c}L{x+w} {y+c}V{y+h-r}A{r} {r} 0 0 1 {x+w-r} {y+h}'
            f'H{x+r}A{r} {r} 0 0 1 {x} {y+h-r}V{y+r}A{r} {r} 0 0 1 {x+r} {y}Z')


def pol(cx, cy, r, deg):
    a = math.radians(deg)
    return cx + r * math.cos(a), cy + r * math.sin(a)


def _history():
    cx, cy, r = 12, 12.5, 8
    x0, y0 = pol(cx, cy, r, 168)        # shaft tail
    x1, y1 = pol(cx, cy, r, 232)        # arrow tip; travel is counter-clockwise
    shaft = f'M{x0:.2f} {y0:.2f}A{r} {r} 0 1 0 {x1:.2f} {y1:.2f}'
    th = math.radians(232)
    bx, by = -math.sin(th), math.cos(th)  # pointing back along the shaft
    L = 3.4
    arms = []
    for s in (45, -45):
        a = math.radians(s)
        arms.append((x1 + L * (bx * math.cos(a) - by * math.sin(a)), y1 + L * (bx * math.sin(a) + by * math.cos(a))))
    head = f'M{arms[0][0]:.2f} {arms[0][1]:.2f}L{x1:.2f} {y1:.2f}L{arms[1][0]:.2f} {arms[1][1]:.2f}'
    d0, d1 = pol(cx, cy, r, 184), pol(cx, cy, r, 194)   # trailing dash, behind the tail
    dash = f'M{d0[0]:.2f} {d0[1]:.2f}A{r} {r} 0 0 1 {d1[0]:.2f} {d1[1]:.2f}'
    return [P(shaft), P(head), P(dash), P('M12 8.75V12.5L14.75 14.25')]


