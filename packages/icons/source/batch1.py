def arc(cx, cy, r, a0, a1):
    x0, y0 = cx + r * math.cos(math.radians(a0)), cy + r * math.sin(math.radians(a0))
    x1, y1 = cx + r * math.cos(math.radians(a1)), cy + r * math.sin(math.radians(a1))
    return f'M{x0:.2f} {y0:.2f}A{r} {r} 0 0 1 {x1:.2f} {y1:.2f}'


def head(cx, cy, r, a, s=1.9):
    t = math.radians(a)
    x, y = cx + r * math.cos(t), cy + r * math.sin(t)
    dx, dy = -math.sin(t), math.cos(t)  # travel direction (clockwise)
    b1 = (x - s * (dx + dy) * .7071 * 1.0, y - s * (dy - dx) * .7071)
    b2 = (x - s * (dx - dy) * .7071, y - s * (dy + dx) * .7071)
    return f'M{b1[0]:.2f} {b1[1]:.2f}L{x:.2f} {y:.2f}L{b2[0]:.2f} {b2[1]:.2f}'


def pt(cx, cy, r, a):
    return cx + r * math.cos(math.radians(a)), cy + r * math.sin(math.radians(a))


