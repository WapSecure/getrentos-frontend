def rays(cx, cy, r0, r1, n=8, rot=0):
    out = []
    for i in range(n):
        a = math.radians(rot + i * 360 / n)
        out.append(P(f'M{cx + r0 * math.cos(a):.2f} {cy + r0 * math.sin(a):.2f}L{cx + r1 * math.cos(a):.2f} {cy + r1 * math.sin(a):.2f}'))
    return out


def pixels(cx, cy, r, n=8, rot=0, s=.95):
    return [dot(round(cx + r * math.cos(math.radians(rot + i * 360 / n)), 2),
                round(cy + r * math.sin(math.radians(rot + i * 360 / n)), 2), s) for i in range(n)]


