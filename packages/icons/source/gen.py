"""Bakes the icon definitions into the @sureground/icons package source.

Usage (from this folder): python3 gen.py ..
Reads icons.py + batch*.py, applies the signature details (cut corner, live ring, pixels)
and writes src/nodes.ts, src/index.ts (web) and src/native.ts (React Native).
"""
import glob, importlib, json, math, os, sys
import icons
from render2 import chamfer_rect, gap_ring

ALL = dict(icons.ICONS)
NOCUT = {'Wallet'}
for f in sorted(glob.glob('batch[0-9].py')):
    m = importlib.import_module(f[:-3])
    ALL.update(m.ICONS)
    NOCUT.update(getattr(m, 'NOCUT', ()))

plan = {'groups': json.load(open(os.path.join(os.path.dirname(__file__), 'names.json')))}


def r2(v):
    return float(f'{v:.2f}') if isinstance(v, float) else v


def bake(name):
    """-> list of [tag, attrs, kind]; kind 's' = stroke, 't' = tint, 'f' = solid fill."""
    out = []
    for tag, a, role in ALL[name]:
        a = {k: r2(v) for k, v in a.items()}
        if role == 'dot':
            s = round(a['r'] * 1.9, 2)
            out.append(['rect', {'x': r2(a['cx'] - s / 2), 'y': r2(a['cy'] - s / 2), 'width': s, 'height': s, 'rx': round(s * 0.18, 2)}, 'f'])
            continue
        geo_tag, geo = tag, a
        if tag == 'rect' and role in ('shape', 'duo') and name not in NOCUT:
            geo_tag, geo = 'path', {'d': chamfer_rect(a['x'], a['y'], a['width'], a['height'], a['rx'], 3.6)}
        if role in ('duo', 'shape'):
            out.append([geo_tag, geo, 't'])
        if role in ('line', 'shape'):
            if tag == 'circle' and role == 'shape' and a['r'] >= 6:
                d, (px, py) = gap_ring(a['cx'], a['cy'], a['r'])
                out.append(['path', {'d': d}, 's'])
                out.append(['rect', {'x': r2(px - 0.95), 'y': r2(py - 0.95), 'width': 1.9, 'height': 1.9, 'rx': 0.35,
                                     'transform': f'rotate(45 {px:.2f} {py:.2f})'}, 'f'])
            else:
                out.append([geo_tag, geo, 's'])
    return out


def main(pkg):
    names = {}  # exported name -> glyph key
    for glyph, members in plan['groups'].items():
        drawn = next((m for m in members if m in ALL), None)
        for m in members:
            if drawn:
                names[m] = drawn
    for n in ALL:
        names.setdefault(n, n)
    missing = sorted({m for g in plan['groups'].values() for m in g} - set(names))
    glyphs = sorted(set(names.values()))
    src = os.path.join(pkg, 'src')
    os.makedirs(src, exist_ok=True)
    hdr = '// Generated by the icon pipeline from the Sureground icon definitions. Do not edit by hand.\n'
    with open(os.path.join(src, 'nodes.ts'), 'w') as f:
        f.write(hdr + "import type { IconNode } from './types';\n\n")
        for g in glyphs:
            f.write(f'export const {g}: IconNode = {json.dumps(bake(g), separators=(",", ":"))};\n')
    for fname, factory in (('index.ts', 'createIcon'), ('native.ts', 'createNativeIcon')):
        mod = './createIcon' if fname == 'index.ts' else './createNativeIcon'
        with open(os.path.join(src, fname), 'w') as f:
            f.write(hdr + f"import {{ {factory} }} from '{mod}';\nimport * as n from './nodes';\n\n")
            if fname == 'index.ts':
                f.write("export type { SgIcon, SgIconProps, IconNode } from './types';\n\n")
            else:
                f.write("export type { IconNode } from './types';\n"
                        "export type { SgNativeIcon, SgNativeIconProps } from './nativeTypes';\n"
                        "export type { SgNativeIcon as SgIcon, SgNativeIconProps as SgIconProps } from './nativeTypes';\n\n")
            for name in sorted(names):
                f.write(f"export const {name} = {factory}('{name}', n.{names[name]});\n")
    print(f'glyphs {len(glyphs)}  exported names {len(names)}  missing {missing}')


if __name__ == '__main__':
    main(sys.argv[1])
